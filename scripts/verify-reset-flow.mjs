import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new" });
const pg = await b.newPage();
await pg.goto("http://localhost:3120/forgot-password", { waitUntil: "networkidle0" });
await pg.type("input[type=email]", "checker@chungpa.local");
await pg.click("form button");
await new Promise((r) => setTimeout(r, 3000));
const list = await (await fetch("http://127.0.0.1:54324/api/v1/messages")).json();
const detail = await (await fetch("http://127.0.0.1:54324/api/v1/message/" + list.messages[0].ID)).json();
const link = ((detail.HTML || "") + (detail.Text || "")).match(/http:\/\/127[^"'\s<)\]]+/)[0].replace(/&amp;/g, "&");
await pg.goto(link, { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 2000));
console.log("STEP 진입:", pg.url().split("?")[0], "| body:", (await pg.evaluate(() => document.body.innerText.slice(0, 60))).replace(/\n/g, " "));
await pg.waitForSelector("input[type=password]", { timeout: 8000 });
await pg.type("input[type=password]", "checker-new-2026!");
await Promise.all([pg.click("form button"), pg.waitForNavigation({ waitUntil: "networkidle0", timeout: 10000 }).catch(() => {})]);
await new Promise((r) => setTimeout(r, 1500));
console.log("STEP 변경 후:", pg.url());
const ctx = await b.createBrowserContext();
const pg2 = await ctx.newPage();
await pg2.goto("http://localhost:3120/login", { waitUntil: "networkidle0" });
await pg2.type("input[type=email]", "checker@chungpa.local");
await pg2.type("input[type=password]", "checker-new-2026!");
await Promise.all([pg2.click("form button"), pg2.waitForNavigation({ waitUntil: "networkidle0" }).catch(() => {})]);
await new Promise((r) => setTimeout(r, 1200));
console.log("STEP 재로그인:", pg2.url().includes("/check") ? "✅ 성공" : "❌ " + pg2.url());
await b.close();
